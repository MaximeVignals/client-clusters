const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  loadData: () => ipcRenderer.invoke('data:load'),
  saveData: data => ipcRenderer.invoke('data:save', data),
  restoreDailyBackup: file => ipcRenderer.invoke('data:restoreDaily', file),
  openDataFolder: () => ipcRenderer.invoke('data:openFolder'),
  saveBackup: opts => ipcRenderer.invoke('backup:save', opts),
  openBackup: () => ipcRenderer.invoke('backup:open'),
  unlockBackupKey: password => ipcRenderer.invoke('backup:unlockKey', password),
  applyBackup: opts => ipcRenderer.invoke('backup:apply', opts),
  openImportFile: () => ipcRenderer.invoke('import:open'),
  openProspectFile: () => ipcRenderer.invoke('prospect:open'),
  exportXlsx: payload => ipcRenderer.invoke('export:xlsx', payload),
  exportKmz: payload => ipcRenderer.invoke('export:kmz', payload),
  geocode: req => ipcRenderer.invoke('geo:geocode', req),
  townAt: req => ipcRenderer.invoke('geo:town', req),
  openExternal: url => ipcRenderer.invoke('app:openExternal', url),
  googleKeyStatus: () => ipcRenderer.invoke('google:keyStatus'),
  googleSetKey: key => ipcRenderer.invoke('google:setKey', key),
  googleSearch: req => ipcRenderer.invoke('google:search', req),
  googleDetails: placeId => ipcRenderer.invoke('google:details', placeId),
  googleResolveLink: url => ipcRenderer.invoke('google:resolveLink', url),
  syncStatus: () => ipcRenderer.invoke('sync:status'),
  syncPause: paused => ipcRenderer.invoke('sync:pause', !!paused),
  syncTest: url => ipcRenderer.invoke('sync:test', url),
  syncEnable: opts => ipcRenderer.invoke('sync:enable', opts),
  syncDisable: () => ipcRenderer.invoke('sync:disable'),
  syncAddPhone: name => ipcRenderer.invoke('sync:addPhone', name),
  syncListPhones: () => ipcRenderer.invoke('sync:listPhones'),
  syncRevokePhone: id => ipcRenderer.invoke('sync:revokePhone', id),
  syncNow: () => ipcRenderer.invoke('sync:now'),
  syncCopyPairing: () => ipcRenderer.invoke('sync:copyPairing'),
  syncClearPairing: () => ipcRenderer.invoke('sync:clearPairing'),
  syncConfirmDeletes: answer => ipcRenderer.invoke('sync:confirmDeletes', answer),
  syncRebase: () => ipcRenderer.invoke('sync:rebase'),
  syncRekey: () => ipcRenderer.invoke('sync:rekey'),
  syncApplied: (id, ok) => ipcRenderer.invoke('sync:applied', id, !!ok),
  onSyncIncoming: cb => { ipcRenderer.on('sync:incoming', (_e, payload) => cb(payload)); },
  onSyncConfirmDeletes: cb => { ipcRenderer.on('sync:confirm-deletes', (_e, counts) => cb(counts)); },
  onSyncStatus: cb => { ipcRenderer.on('sync:status-changed', (_e, s) => cb(s)); },
});
